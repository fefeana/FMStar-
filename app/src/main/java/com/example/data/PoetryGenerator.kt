package com.example.data

import com.example.model.PoetryItem
import com.example.model.PoetryVerse
import java.text.SimpleDateFormat
import java.util.Date
import java.util.Locale

object PoetryGenerator {

    val availableDialects = listOf(
        "يمني صنعاني",
        "خليجي نبطي",
        "عربي فصيح",
        "حضرمي دان",
        "خواطر غنائية"
    )

    val availableMoods = listOf(
        "غزل وطرب",
        "شوق وحنين",
        "فخر وحكمة",
        "سهر وأشجان"
    )

    fun generatePoem(dialect: String, mood: String, customTopic: String = ""): PoetryItem {
        val dateStr = SimpleDateFormat("yyyy-MM-dd HH:mm", Locale.getDefault()).format(Date())
        
        val (title, verses) = when (dialect) {
            "يمني صنعاني" -> when (mood) {
                "غزل وطرب" -> Pair(
                    "نسيم الشوق في صنعاء القديمة",
                    listOf(
                        PoetryVerse("يا غصن موزر في رياض الأماني", "سَلبتَ عقلي بالعيون الحِسانِ"),
                        PoetryVerse("بِالله رفقاً بالمُعنّى المُتيّم", "صَبٌّ على بابِ الملاح انحناني"),
                        PoetryVerse("صنعاء حَوَت كُل البَهاءِ وتاجُها", "نورٌ تلألأ في جبين الغواني"),
                        PoetryVerse("إن غاب صوتُك فالأنينُ نديمي", "والوجدُ يسري في صميم جناني")
                    )
                )
                "شوق وحنين" -> Pair(
                    "حنين الدان من قمة نقم",
                    listOf(
                        PoetryVerse("يا طير شادي فوق غصن البلس", "سلّم على خلّي وبدّد شجاني"),
                        PoetryVerse("الشوق ناره في فؤادي تلظت", "والبعد ضيّع فرحتي والتهاني"),
                        PoetryVerse("يا ليتني نسمة هوا في ديارهم", "ألثم خدود الزين في كل آنِ"),
                        PoetryVerse("أشكي لمن ما حل بي في غيابهم", "والصبر غلّق والزمان ابتلاني")
                    )
                )
                "فخر وحكمة" -> Pair(
                    "أصالة حِميَر وعزة اليماني",
                    listOf(
                        PoetryVerse("نحنُ اليمانون أهلُ العزمِ والظفرِ", "تاريخُنا ساطعٌ كالشمسِ والقمرِ"),
                        PoetryVerse("ما لانَ هامتُنا يوماً لنائبةٍ", "والصبرُ فينا وثيقُ العهدِ والأثرِ"),
                        PoetryVerse("كرمٌ وشيمةُ أجدادٍ نلوذُ بها", "يبقى سَنَاها منيعاً طيلةَ العُمُرِ"),
                        PoetryVerse("في هامةِ المجدِ راياتٌ نخلدها", "يشهد لنا الدهر في بدوٍ وفي حضرِ")
                    )
                )
                else -> Pair(
                    "نجوى السمر في ليل صنعاء",
                    listOf(
                        PoetryVerse("سريتُ في الليل والذكرى تؤرقني", "والطيرُ ساجٍ على أغصانِ كرمتِنا"),
                        PoetryVerse("صوتُ العقيقِ سرى كالسحرِ في خلدي", "يُعيدُ ما كانَ من أنسامِ فرحتِنا"),
                        PoetryVerse("يا سامعي في سكونِ الكونِ قافيتي", "إن النجومَ شهودٌ فوقَ قِمتِنا")
                    )
                )
            }
            "خليجي نبطي" -> when (mood) {
                "غزل وطرب" -> Pair(
                    "سحر العيون وشوق النواظر",
                    listOf(
                        PoetryVerse("يا زين ما شفت مثلك في هوى البيدِ", "نورك يشع بنواظر كل خلاني"),
                        PoetryVerse("عينك سهام الموت لامن رميت بها", "والخد بارق سنا يضوي بوجداني"),
                        PoetryVerse("حبك جرى في خفوقي مثل وبل الغيث", "يحيي هشيم المشاعر بين الأعيانِ"),
                        PoetryVerse("أنت الملك في فوادي والعرش ملكك", "ولك العهد والوفا دايم مع أزماني")
                    )
                )
                "فخر وحكمة" -> Pair(
                    "وقفة شموخ وعزم الأصايل",
                    listOf(
                        PoetryVerse("الطيب ساس الفتى والعز منهجه", "والمرجلة كايدة ما كل من طالها"),
                        PoetryVerse("نمشي على وضح النقا ما نهاب الخطر", "وروس المعالي لنا والمجد نزها لها"),
                        PoetryVerse("يا ناشدٍ عن سلوم القوم وافعالها", "تلقى المكارم ذرى والخير فِـ اقبالها"),
                        PoetryVerse("يبقى الشهم في مدار المجد متصدر", "والوقفة الصادقة بالفعل وازنها")
                    )
                )
                else -> Pair(
                    "ساري مع النجم السهارى",
                    listOf(
                        PoetryVerse("سريت ليل الهوى والنور متخفّي", "أدوّر اللي خذا روحي على هونه"),
                        PoetryVerse("أجرّ صوتي ودمع العين متحفّي", "والقلب يشكي فراق اللي يعرفونه"),
                        PoetryVerse("يا ليت من هو بقرب الصاحب الوفي", "تسلى عيونه وتضحك نبرة جنونه")
                    )
                )
            }
            "حضرمي دان" -> Pair(
                "طرب الدان في حضرموت الوادي",
                listOf(
                    PoetryVerse("يا دان دان الدان يا نسمة سحر", "عطّر ضواحي شبام وأسعد الحارة"),
                    PoetryVerse("في وادي الأحقاف نغمات الوتر", "تشفي قلوب الحبايب نغمة الطارة"),
                    PoetryVerse("ليلة صفا عانقت ضوء القمر", "والعود يعزف لنا والخل بأنواره"),
                    PoetryVerse("يا لايمي كف لومك في الأثر", "العشق بلوى وصعبٌ كتم أسراره")
                )
            )
            "عربي فصيح" -> Pair(
                "تراتيل الفجر على أوتار القريض",
                listOf(
                    PoetryVerse("أضاءَ الفجرُ في أُفُقِ السماءِ", "فأشرقتِ المعالمُ بالضياءِ"),
                    PoetryVerse("وسالَ الشهدُ من نغمِ القوافي", "يُداوي جُرحَ صَبٍّ في الخفاءِ"),
                    PoetryVerse("أيا روحَ القصيدِ ألا أفيضي", "على الأسماعِ سحراً من صفاءِ"),
                    PoetryVerse("فما أحلى البيانَ إذا تسامى", "وعانقَ نجمةَ الفلكِ العلاءِ")
                )
            )
            else -> Pair(
                "همسات أثير FMStar",
                listOf(
                    PoetryVerse("عبر الأثيرِ سرت أنغامُ نجمتِنا", "تُعانقُ الليلَ في أشواقِ سمارِ"),
                    PoetryVerse("صوتُ السحابِ غدا لحناً نلوذُ به", "والنبضُ يسري بدفءِ النغمِ والساري"),
                    PoetryVerse("هنا استوديو الخيالِ الرحبِ يجمعُنا", "بين الذكاءِ وشدوِ الشاعرِ الداري")
                )
            )
        }

        return PoetryItem(
            title = if (customTopic.isNotBlank()) "قصيدة في $customTopic ($dialect)" else title,
            dialect = dialect,
            mood = mood,
            verses = verses,
            author = "استوديو جيمي & ميرا الذكي",
            date = dateStr,
            isSavedToCloud = true,
            isFavorite = false,
            hasRecitation = true
        )
    }
}
